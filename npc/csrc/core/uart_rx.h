/***************************************************************************************
* NPC UART Receiver (仿真侧)
* 采样 ysyxSoC UART16550 输出的串行引脚 uart_tx, 解码出字符并输出到终端.
*
* 工作原理: UART16550 发送端按 (16 * divisor) 个时钟周期/位 的速率串行发送,
*   空闲时 uart_tx=1, 起始位为 0, 之后是 8 个数据位 (LSB first), 最后是停止位 1.
*   本接收机在每个时钟周期采样 uart_tx, 用状态机在每位的中间位置采样, 还原出字节.
*   注: 软件初始化时设置的 divisor 越小, 波特率越高, 仿真时每个字符花费的周期越少.
***************************************************************************************/

#ifndef __UART_RX_H__
#define __UART_RX_H__

#include <cstdint>

// 每个时钟周期调用一次, 传入当前 uart_tx 引脚电平 (0/1)
void uart_rx_sample(uint8_t uart_tx_pin);

#endif
